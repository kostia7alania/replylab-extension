export const SUPPORTED_LANGUAGES = Object.freeze(['ru', 'en', ...Object.keys(LOCALE_ROWS)]);
export const DICTIONARY = Object.freeze(Object.fromEntries(SOURCE_MESSAGES.map(({ ru, en }, index) => [en,
  Object.freeze({ ru, en, ...Object.fromEntries(Object.entries(LOCALE_ROWS).map(([language, entries]) => [language, entries[index]])) }),
])));
const byRussian = new Map(SOURCE_MESSAGES.map(({ ru, en }) => [ru, en]));

export function translate(ru, en, language = 'ru') {
  if (language === 'ru') return ru;
  if (language === 'en' || !SUPPORTED_LANGUAGES.includes(language)) return en;
  const key = Object.hasOwn(DICTIONARY, en) ? en : byRussian.get(ru);
  const translated = key && DICTIONARY[key][language];
  if (typeof translated !== 'string' || !translated.trim()) {
    throw new RangeError(`Missing ${language} translation: ${en}`);
  }
  return translated;
}
